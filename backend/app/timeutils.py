"""Время в проекте: хранится в UTC, показывается и планируется по Москве.

Календарная дата — единственное место, где эти два пояса расходятся по
существу: `date.today()` берёт дату по часовому поясу процесса, а контейнер
живёт в UTC. Расписание фоновых задач объявлено в московском поясе
(`MOSCOW_TZ` ниже используется и планировщиком), торговый день MOEX — тоже
московский. Вечерний снимок в 19:30 по Москве при `date.today()` пишется под
датой предыдущих суток UTC ровно с 00:00 до 03:00 MSK; сейчас в это окно ни
одна задача не попадает, но связь была неявной и держалась на расписании.
"""

from datetime import date, datetime
from zoneinfo import ZoneInfo

MOSCOW_TZ = ZoneInfo("Europe/Moscow")


def moscow_now() -> datetime:
    return datetime.now(tz=MOSCOW_TZ)


def moscow_today() -> date:
    """Календарная дата по московскому поясу — явно, а не по поясу процесса."""
    return moscow_now().date()
