"""Подпись счёта — одна функция на проект.

Раньше их было две: `app/api/account_labels.py` всегда давал «Имя (внешний
идентификатор)», а аналитика строила подпись сама и добавляла идентификатор
только при совпадении имён. Один и тот же счёт оказывался подписан по-разному
на одном экране — в баннере расхождений так, а в разбивке по счетам иначе, —
хотя документация первой функции прямо обещала обратное.

Выбран безусловный формат «Имя (внешний идентификатор)»: имя само по себе
счёт не определяет (коннектор Т-Банка подставляет заглушку «Счёт», если брокер
имени не дал), а уникальна только пара (broker, external_id). Подпись,
меняющая форму в зависимости от того, какие ещё счета попали в выборку, —
именно то, что делало её непригодной для чего-либо, кроме показа.
"""

from sqlalchemy.orm import Session

from app.models import Account

# Подпись счёта, когда узнать её не из чего (например, у прогона синхронизации
# нет ссылки на счёт — см. account_label_by_id).
UNKNOWN_ACCOUNT_LABEL = "счёт не определён"


def account_label(account: Account) -> str:
    """Читаемая и однозначно различимая подпись счёта для ответов API."""
    return f"{account.name} ({account.external_id})"


def account_label_by_id(session: Session, account_id: int | None) -> str:
    """То же, но когда на руках только идентификатор — и он может отсутствовать
    (SAVEPOINT прогона синхронизации откатывает и сам счёт, если сбой случился
    ещё на его заведении)."""
    if account_id is None:
        return UNKNOWN_ACCOUNT_LABEL
    account = session.get(Account, account_id)
    if account is None:
        return UNKNOWN_ACCOUNT_LABEL
    return account_label(account)
