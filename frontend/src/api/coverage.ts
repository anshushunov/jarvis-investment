import type { Overview } from "./client";

// Почему совокупный капитал посчитан не по всему портфелю. Причин две, и они
// разные настолько, что общая формулировка вводит в заблуждение:
//
// - "prices" — у части бумаг нет котировки. Сколько именно таких, известно
//   точно: positions_total минус valued_positions.
// - "rates"  — нет курса к рублю. Тогда цена как раз есть, но перевести её в
//   рубли нечем, и из итога выпадает всё, что номинировано в этой валюте:
//   бумаги, денежные остатки, золото и прочие металлы. Курсы грузит задача
//   планировщика раз в сутки, так что на свежей базе это состояние — норма
//   первых часов, а не редкий сбой.
//
// Различать их обязательно: сообщение "цены есть только для N позиций" при
// нехватке курса называет неверную причину и уводит от починки.
//
// Валюты для "rates" считает бэкенд (currencies_without_rate) — только он
// знает, какой курс какой суммой был спрошен. Собирать их здесь вычитанием
// «валюты портфеля минус посчитанные» нельзя: у позиции без котировки курс не
// спрашивается вовсе, и её валюта попала бы в список без всякой вины курсов.
export type CoverageWarning =
  | { kind: "rates"; currencies: string[]; valued: number; total: number }
  | { kind: "prices"; valued: number; total: number };

export function coverageWarning(overview: Overview): CoverageWarning | null {
  const { valued_positions: valued, positions_total: total } = overview;
  const currencies = overview.currencies_without_rate;

  // Нехватка курсов идёт первой: она устранима (курс подтянется сам или
  // руками), тогда как отсутствие котировки для гонконгской бумаги — свойство
  // выбранного источника данных. Число посчитанных позиций это сообщение
  // называет тоже, так что вторая причина не теряется, если верны обе.
  if (currencies.length > 0) {
    return { kind: "rates", currencies, valued, total };
  }
  if (total > 0 && valued < total) {
    return { kind: "prices", valued, total };
  }
  return null;
}
